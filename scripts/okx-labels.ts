import { spawn } from "node:child_process";
import { createPublicKey, verify } from "node:crypto";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, join } from "node:path";
import { createInterface } from "node:readline";
import { decodeBase58 } from "../src/util/base58.js";

const url = process.argv[2];
if (!url?.startsWith("https://static.okx.com/")) {
  throw new Error("usage: tsx scripts/okx-labels.ts https://static.okx.com/cdn/okx/por/chain/por_csv_<snapshot>.zip");
}

const HEADER = "OKX Signed Message:\n";

function varString(text: string): Buffer {
  const bytes = Buffer.from(text, "utf8");
  if (bytes.length >= 0xfd) throw new Error("message too long for a one-byte varint");
  return Buffer.concat([Buffer.from([bytes.length]), bytes]);
}

function signedByAddress(address: string, message: string, signature: string, publicKey: string): boolean {
  const key = Buffer.from(publicKey.replace(/^0x/, ""), "hex");
  const decoded = decodeBase58(address);
  if (!decoded || !Buffer.from(decoded).equals(key)) return false;
  const jwk = createPublicKey({ key: { kty: "OKP", crv: "Ed25519", x: key.toString("base64url") }, format: "jwk" });
  return verify(null, Buffer.concat([varString(HEADER), varString(message)]), jwk, Buffer.from(signature.replace(/^0x/, ""), "hex"));
}

const dir = mkdtempSync(join(tmpdir(), "okx-por-"));
try {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`HTTP ${response.status} for ${url}`);
  const zip = join(dir, "por.zip");
  writeFileSync(zip, Buffer.from(await response.arrayBuffer()));

  const unzip = spawn("unzip", ["-p", zip], { stdio: ["ignore", "pipe", "inherit"] });
  const verified = new Set<string>();
  let rejected = 0;
  for await (const line of createInterface({ input: unzip.stdout })) {
    const cols = line.split(",");
    if (cols.length < 10 || cols[2] !== "SOL" || cols[6] !== "I am an OKX address") continue;
    const [, , , , address, , message, signature, , publicKey] = cols;
    if (signedByAddress(address, message, signature, publicKey)) verified.add(address);
    else rejected++;
  }
  if (rejected > 0 || verified.size === 0) throw new Error(`${rejected} Solana rows failed signature checks, ${verified.size} passed`);

  const snapshot = basename(new URL(url).pathname);
  const lines = [...verified].sort();
  writeFileSync(
    "src/labels/okx-solana.ts",
    [
      `// Generated by scripts/okx-labels.ts from ${url}; do not edit.`,
      `export const OKX_SNAPSHOT = ${JSON.stringify({ file: snapshot, url, addresses: lines.length })};`,
      "export const OKX_SOLANA = `",
      ...lines,
      "`;",
      "",
    ].join("\n"),
  );
  console.log(`src/labels/okx-solana.ts: ${lines.length} Solana addresses, every ownership signature verified (${snapshot})`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
